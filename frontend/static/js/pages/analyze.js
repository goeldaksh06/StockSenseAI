import { $, h, mount } from '../core/dom.js';
import { api } from '../core/api.js';
import { money, num, pct, signedPct, tone, isNum } from '../core/format.js';
import { currentUser } from '../core/auth.js';
import { toast, errorBox } from '../core/ui.js';
import { symbolBar } from '../components/symbolBar.js';
import { segmented } from '../components/table.js';
import { lineChart } from '../components/chart.js';
import { term } from '../components/explain.js';
import { setPageContext, getPageContext, round } from '../core/pageContext.js';

const out = $('#out');
let sym = '';
let runId = 0;

function sma(values, n) {
  return values.map((_, i) => (i + 1 < n ? null : values.slice(i + 1 - n, i + 1).reduce((a, b) => a + b, 0) / n));
}

const bar = symbolBar({ initial: document.body.dataset.symbol, onSubmit: load });
$('#bar').append(bar.el);

async function load(symbol) {
  sym = symbol;
  const id = ++runId;
  history.replaceState(null, '', '/analyze/' + symbol);
  document.title = `${symbol} | StockSense`;

  const priceSlot = h('div', {}, h('div', { class: 'state' }, 'Loading prices...'));
  const forecastSlot = h('div', {}, h('div', { class: 'state' }, 'Running model...'));
  const sentimentSlot = h('div', {}, h('div', { class: 'state' }, 'Reading headlines...'));
  const briefSlot = h('div', {});
  mount(out,
    h('div', { class: 'cols', style: 'margin-top:22px' },
      h('div', {}, h('section', { class: 'panel' }, h('h3', {}, symbol, ' price history'), priceSlot)),
      h('div', {}, h('section', { class: 'panel' }, h('h3', {}, 'Next-day forecast'), forecastSlot))),
    h('div', { class: 'cols' },
      h('section', { class: 'panel' }, h('h3', {}, 'AI briefing ', h('span', { class: 'muted', style: 'font:.75rem var(--font-mono)' }, 'explains, does not predict')), briefSlot),
      h('section', { class: 'panel' }, h('h3', {}, term('News sentiment', 'sentiment')), sentimentSlot)));

  // Prices are cheap, so check the ticker first: an unknown symbol should fail once, not three times.
  let prices;
  try { prices = await api.history(symbol, 730); } catch (e) {
    if (id !== runId) return;
    mount(out, e.status === 404
      ? h('div', { class: 'state err' }, `No price data for "${symbol}". Check the ticker (US symbols like AAPL, MSFT, NVDA).`)
      : errorBox(e, () => load(symbol)));
    return;
  }
  if (id !== runId) return;
  renderPrice(priceSlot, prices);
  const ctxData = { price_history: { last_close: round(prices.close.at(-1)), change_over_loaded_period_pct: round((prices.close.at(-1) / prices.close[0] - 1) * 100), days_loaded: prices.close.length } };
  setPageContext({ page: 'analyze', symbol, data: ctxData });
  api.predict(symbol).then((p) => { if (id === runId) renderForecast(forecastSlot, p); })
    .catch((e) => { if (id === runId) mount(forecastSlot, errorBox(e, () => load(symbol))); });
  loadBriefing(symbol, id, briefSlot, sentimentSlot);
}

async function loadBriefing(symbol, id, briefSlot, sentimentSlot) {
  mount(briefSlot, h('div', { class: 'state' }, 'Writing briefing...'));
  try {
    const d = await api.briefing(symbol);
    if (id !== runId) return;
    renderSentiment(sentimentSlot, d.sentiment);
    const b = d.briefing;
    mount(briefSlot,
      b.available
        ? h('div', { class: 'prose', style: 'white-space:pre-wrap' }, b.text)
        : h('div', {}, h('p', { class: 'muted' }, 'Briefing unavailable. ', b.text?.startsWith('Briefing generation failed') ? 'The language model provider rejected the request; check the API key on the server.' : b.text),
          h('button', { class: 'btn ghost small', onclick: () => loadBriefing(symbol, id, briefSlot, sentimentSlot) }, 'Retry')),
      h('p', { class: 'muted', style: 'font-size:.75rem' }, b.available ? `Generated by ${b.provider}.` : ''));
  } catch (e) {
    if (id !== runId) return;
    mount(briefSlot, errorBox(e, () => loadBriefing(symbol, id, briefSlot, sentimentSlot)));
    mount(sentimentSlot, errorBox(e));
  }
}

function renderPrice(slot, d) {
  let range = 126;
  let showSma20 = true, showSma50 = false;
  const dates = d.dates, close = d.close;
  const s20 = sma(close, 20), s50 = sma(close, 50);

  const build = () => {
    const from = Math.max(0, close.length - range);
    const series = [{ name: 'Close', color: 'ink', dates: dates.slice(from), values: close.slice(from) }];
    if (showSma20) series.push({ name: 'SMA 20', color: 'accent', dates: dates.slice(from), values: s20.slice(from), width: 1.2 });
    if (showSma50) series.push({ name: 'SMA 50', color: 'warn', dates: dates.slice(from), values: s50.slice(from), width: 1.2, dash: true });
    return series;
  };
  const chart = lineChart({ series: build(), yFormat: (v) => '$' + v.toFixed(2), label: `${sym} closing price` });
  const redraw = () => chart.update({ series: build() });
  const first = close[Math.max(0, close.length - range)], last = close.at(-1);

  const stat = h('p', { class: 'num' });
  const setStat = () => {
    const f = close[Math.max(0, close.length - range)];
    const ch = ((last / f) - 1) * 100;
    mount(stat, money(last), ' ', h('span', { class: tone(ch) }, signedPct(ch), ' over range'));
  };
  setStat();

  mount(slot,
    stat,
    h('div', { style: 'display:flex;gap:12px;flex-wrap:wrap;margin-bottom:10px' },
      segmented([{ label: '1M', value: 21 }, { label: '3M', value: 63 }, { label: '6M', value: 126 }, { label: '1Y', value: 252 }, { label: '2Y', value: 504 }], range, (v) => { range = v; setStat(); redraw(); }, 'Range'),
      h('label', { class: 'field', style: 'flex-direction:row;align-items:center;gap:6px' }, h('input', { type: 'checkbox', checked: true, onchange: (e) => { showSma20 = e.target.checked; redraw(); } }), 'SMA 20'),
      h('label', { class: 'field', style: 'flex-direction:row;align-items:center;gap:6px' }, h('input', { type: 'checkbox', onchange: (e) => { showSma50 = e.target.checked; redraw(); } }), 'SMA 50')),
    chart);
}

function gauge(label, value, lo, hi, marks) {
  const p = isNum(value) ? Math.max(0, Math.min(100, ((value - lo) / (hi - lo)) * 100)) : 0;
  return h('div', { style: 'margin:12px 0' },
    h('div', { style: 'display:flex;justify-content:space-between;font-size:.8rem' }, h('span', { class: 'muted' }, label), h('span', { class: 'num' }, num(value, 1))),
    h('div', { class: 'meter' }, h('i', { style: `left:${p}%` })),
    h('div', { class: 'muted', style: 'display:flex;justify-content:space-between;font:.68rem var(--font-mono)' }, ...marks.map((m) => h('span', {}, m))));
}

function renderForecast(slot, p) {
  setPageContext({ page: 'analyze', symbol: sym, data: { ...getPageContext().data, next_day_forecast: { current_price: p.current_price, predicted_price: p.predicted_price, expected_move_pct: p.predicted_return_pct, direction: p.direction, confidence: p.direction_confidence, as_of: p.as_of_date, indicators: p.indicators } } });
  const up = p.direction === 'up';
  const watchBtn = h('button', { class: 'btn ghost small', type: 'button' }, 'Add to watchlist');
  watchBtn.onclick = async () => {
    if (!(await currentUser())) { location.assign('/login?next=' + encodeURIComponent(location.pathname)); return; }
    try { await api.addWatch(sym); toast(`${sym} added to watchlist`); watchBtn.disabled = true; }
    catch (e) { toast(e.message, true); }
  };
  const ind = p.indicators || {};
  mount(slot,
    h('dl', { class: 'kv', style: 'grid-template-columns:1fr 1fr' },
      h('div', {}, h('dt', {}, 'Predicted close'), h('dd', {}, money(p.predicted_price))),
      h('div', {}, h('dt', {}, 'Expected move'), h('dd', { class: tone(p.predicted_return_pct) }, signedPct(p.predicted_return_pct))),
      h('div', {}, h('dt', {}, 'Direction'), h('dd', { class: up ? 'up' : 'down' }, up ? 'Up' : 'Down')),
      h('div', {}, h('dt', {}, term('Confidence', 'confidence')), h('dd', {}, pct((p.direction_confidence || 0) * 100, 0)))),
    h('p', { class: 'muted', style: 'font-size:.78rem;margin-top:10px' }, 'Confidence near 50% is a coin flip. Historically this model has not beaten the naive baseline; see ', h('a', { href: '/models' }, 'Models'), '.'),
    gauge(term('RSI (14)', 'rsi'), ind.rsi, 0, 100, ['0', '30', '70', '100']),
    h('p', { class: 'muted num', style: 'font-size:.78rem' }, ...[term('MACD', 'macd'), ` ${num(ind.macd, 2)} vs signal ${num(ind.signal_line, 2)} | `, term('SMA 20', 'sma'), ` ${money(ind.ema_20)}`]),
    h('p', { class: 'muted', style: 'font-size:.75rem' }, `As of ${p.as_of_date}`),
    watchBtn);
}

function renderSentiment(slot, sent) {
  // Scores only: headline text is third-party content and is kept out of the assistant's context.
  setPageContext({ page: 'analyze', symbol: sym, data: { ...getPageContext().data, news_sentiment: { overall_score: sent.overall_score, label: sent.label, positive_pct: sent.positive_pct, neutral_pct: sent.neutral_pct, negative_pct: sent.negative_pct, headline_count: (sent.headlines || []).length } } });
  const heads = sent.headlines || [];
  let filter = 'All';
  const list = h('ul', { class: 'list' });
  const draw = () => mount(list, ...heads.filter((x) => filter === 'All' || x.label === filter).map((x) =>
    h('li', {}, h('span', {}, x.title), h('span', { class: 'tag ' + (x.label === 'Positive' ? 'up' : x.label === 'Negative' ? 'down' : 'muted') }, x.label))));
  draw();
  mount(slot,
    h('dl', { class: 'kv', style: 'grid-template-columns:repeat(3,1fr)' },
      h('div', {}, h('dt', {}, 'Positive'), h('dd', { class: 'up' }, pct(sent.positive_pct, 0))),
      h('div', {}, h('dt', {}, 'Neutral'), h('dd', {}, pct(sent.neutral_pct, 0))),
      h('div', {}, h('dt', {}, 'Negative'), h('dd', { class: 'down' }, pct(sent.negative_pct, 0)))),
    h('p', { class: 'muted', style: 'font-size:.8rem;margin:10px 0' }, `Overall ${sent.label} (${num(sent.overall_score, 2)})`),
    heads.length ? segmented(['All', 'Positive', 'Neutral', 'Negative'].map((v) => ({ label: v, value: v })), filter, (v) => { filter = v; draw(); }, 'Filter headlines') : h('p', { class: 'muted' }, 'No headlines found.'),
    list);
}

if (document.body.dataset.symbol) bar.go(document.body.dataset.symbol);
